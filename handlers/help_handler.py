def get_topic_names() -> List[str]:
    """所有系统详解的主题名（按 HELP_TOPICS 定义顺序）"""
    return list(HELP_TOPICS.keys())


def normalize_topic(topic: str) -> Optional[str]:
    """把用户输入的主题名规范化为 HELP_TOPICS 的键，未匹配返回 None"""
    if not topic:
        return None
    text = str(topic).strip().replace("帮助", "").strip()
    if text in HELP_TOPICS:
        return text
    if text in TOPIC_ALIASES:
        return TOPIC_ALIASES[text]
    return None


class HelpHandler:
    """系统详解帮助处理器"""

    async def handle_topic(self, event, topic: str):
        """<系统>帮助 指令入口"""
        text = self.render_topic(topic)
        yield event.plain_result(text if text else self.suggest(topic))

    async def handle_index(self, event):
        """帮助索引指令入口"""
        yield event.plain_result(self.render_overview())

    def render_topic(self, topic: str) -> Optional[str]:
        """渲染指定系统的详细帮助，未匹配返回 None"""
        key = normalize_topic(topic)
        if not key:
            return None
        return self._render(key, HELP_TOPICS[key])

    def render_overview(self) -> str:
        """系统详解帮助索引"""
        lines = ["📚 系统详解帮助", _SEP, "使用「<系统>帮助」查看详细玩法，例如「宗门帮助」「组队帮助」。", ""]
        for name, topic in HELP_TOPICS.items():
            lines.append(f"  {topic['emoji']} {name}帮助")
        lines.append("")
        lines.append("💡 也可以使用「修仙帮助 <系统>」，例如：修仙帮助 宗门")
        return "\n".join(lines)

    def suggest(self, topic: str) -> str:
        """未匹配时的提示"""
        names = "、".join(HELP_TOPICS.keys())
        return (
            f"❌ 未找到系统「{topic}」的帮助\n"
            f"可用系统：{names}\n"
            "💡 也可直接发送「修仙帮助」查看总览"
        )

    def _render(self, name: str, topic: dict) -> str:
        lines = [f"{topic['emoji']} {topic['title']}", _SEP]
        intro = topic.get("intro")
        if intro:
            lines.append(intro)
            lines.append("")

        for section_title, items in topic.get("sections", []):
            lines.append(f"【{section_title}】")
            for item in items:
                lines.append(f"  {item}")
            lines.append("")

        tips = topic.get("tips") or []
        if tips:
            lines.append("💡 提示")
            for tip in tips:
                lines.append(f"  · {tip}")

        return "\n".join(lines).rstrip()
